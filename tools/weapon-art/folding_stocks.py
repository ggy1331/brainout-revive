"""Folding stocks for the SPAS-12 and the Protecta (GGY, 2026-11-13).

Both guns are drawn with the stock folded over the receiver; an upgrade "Unfolded Buttstock"
(ITEM_UPGRADE_UNFOLDED_BUTT, like the Honey Badger's) unfolds it: accuracy +10, recoil -10, a bit
slower to move with (speed-coef *0.95).

  SPAS-12   the folded stock is its own slot ("butt", attachment "default" per skin); unfolded =
            the same picture turned 180 degrees about the hinge at the back of the receiver.
  Protecta  the folded stock is drawn into the body: protecta-skin(-river)-unfolded.png are the
            bodies with it removed (the light arc over the receiver and its bend at the back), and
            the unused protecta-butt-unfold.png goes on a new "butt" slot behind the body.

Edits the source skeletons, writes the upgrade files and adds the "butt" row to the Store Items;
re-running gives the same result.
    python tools/weapon-art/folding_stocks.py
then make_data client + server (the new pictures go into the atlas).
"""
import json
import os
import re
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
BASE = os.path.join(ROOT, "data", "packages", "base")
GAME = os.path.join(BASE, "textures", "GAME")
ANIM = os.path.join(BASE, "contents", "content", "animations")
WEAP = os.path.join(BASE, "smart", "Weapons")

SPAS_HINGE = (-5.5, 12.5)          # root units: the stock turns about this point
PROPS = {"accuracy": "+10", "recoil": "-10", "speed-coef": "*0.95"}


def upgrade(uid, replace, icon):
    rows = "\n".join("            %s = %s" % kv for kv in replace.items())
    props = "\n".join('    %s = "%s"' % kv for kv in PROPS.items())
    return """// Generated by tools/weapon-art/folding_stocks.py - edit the script, not this file.
access = byDefault
class = content.upgrades.Upgrade
components = [
    {
        class = content.components.ReplaceSlotComponent
        classToReplace = data.components.WeaponAnimationComponentData
        replace = {
%s
        }
        tag = client
    }
    {
        big-icon = %s
        class = content.components.IconComponent
        tag = client
    }
]
description = ITEM_UPGRADE_UNFOLDED_BUTT_DESC
id = %s
name = ITEM_UPGRADE_UNFOLDED_BUTT
properties = {
%s
}
""" % (rows, icon, uid, props)


def write_upgrade(folder, uid, replace, icon):
    with open(os.path.join(WEAP, folder, "Upgrades", "Unfolded Butt.txt"), "w", encoding="utf-8", newline="\r\n") as f:
        f.write(upgrade(uid, replace, icon))
    store = os.path.join(WEAP, folder, "Store Item.txt")
    text = open(store, encoding="utf-8").read()
    if uid not in text:
        text = re.sub(r"(    upgrades = \{\r?\n)", lambda m: m.group(1) + "        butt = %s\r\n" % uid, text, count=1)
        open(store, "w", encoding="utf-8", newline="").write(text)


def load(name):
    p = os.path.join(ANIM, name + ".json")
    return p, json.load(open(p, encoding="utf-8"))


def save(p, d):
    with open(p, "w", encoding="utf-8") as f:
        json.dump(d, f, ensure_ascii=False, indent=1)
        f.write("\n")


def spas12():
    p, d = load("weapon-spas12")
    hx, hy = SPAS_HINGE
    for skin in d["skins"]:
        butt = skin.get("attachments", {}).get("butt", {})
        folded = butt.get("default")
        if not folded:
            continue
        un = dict(folded)
        un["x"] = round(2 * hx - folded.get("x", 0), 4)
        un["y"] = round(2 * hy - folded.get("y", 0), 4)
        un["rotation"] = 180
        un.setdefault("name", "spas12-butt-default")
        butt["unfolded"] = un
    save(p, d)
    write_upgrade("spas12", "upgrade-spas12-butt-unfolded", {"butt": "unfolded"}, "spas12-butt-default")


def clean_protecta(name):
    """the body without the folded stock: the light arc over the receiver and its bend at the back"""
    b = Image.open(os.path.join(GAME, name + ".png")).convert("RGBA")
    px = b.load()
    for x in range(b.width):
        for y in range(b.height):
            r, g, bl, a = px[x, y]
            if a < 10:
                continue
            light = g > r + 6 or (r > 140 and g > 140)
            if (y <= 4 and x >= 8) or (y <= 5 and 14 <= x <= 67) or (x < 14 and y <= 11 and light):
                px[x, y] = (0, 0, 0, 0)
    out = name + "-unfolded"
    b.save(os.path.join(GAME, out + ".png"))
    return out


def protecta():
    p, d = load("weapon-protecta")
    names = [s["name"] for s in d["slots"]]
    if "butt" not in names:
        d["slots"].insert(names.index("body"), {"name": "butt", "bone": "root"})
    stock = Image.open(os.path.join(GAME, "protecta-butt-unfold.png"))
    for skin in d["skins"]:
        atts = skin.setdefault("attachments", {})
        body = atts.get("body", {}).get("body")
        if not body:
            continue
        left = body.get("x", 0) - body["width"] / 2
        top = body.get("y", 0) + body["height"] / 2
        clean = clean_protecta(body.get("name", "protecta-skin"))
        atts["body"]["unfolded"] = dict(body, name=clean)
        # the hinge end of the stock (its right end) at the back of the receiver, 1 px below its top
        atts.setdefault("butt", {})["unfolded"] = {
            "name": "protecta-butt-unfold", "width": stock.width, "height": stock.height,
            "x": round(left - stock.width + 6 + stock.width / 2, 4),
            "y": round(top - 1 - stock.height / 2, 4)}
    save(p, d)
    write_upgrade("protecta", "upgrade-protecta-butt-unfolded", {"body": "unfolded", "butt": "unfolded"},
                  "protecta-butt-unfold")


if __name__ == "__main__":
    spas12()
    protecta()
    print("ok")
